/**
 * Downloads all rendered visuals as individual PNG files with staggered delay.
 */
export async function downloadAllFlyersAsPng(posts: PostItem[], brandName: string): Promise<number> {
  const readyPosts = posts.filter((p) => p.visualStatus === 'READY' && p.imageUrl);
  if (readyPosts.length === 0) return 0;

  for (let i = 0; i < readyPosts.length; i++) {
    const post = readyPosts[i];
    await downloadPostFlyerAsPng(post, brandName);
    // 350ms delay between downloads to prevent browser download throttling
    if (i < readyPosts.length - 1) {
      await new Promise((resolve) => setTimeout(resolve, 350));
    }
  }

  return readyPosts.length;
}

/**
 * Helper to trigger a direct file download.
 */
function triggerDownload(url: string, filename: string) {
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
